"""Builds js/i18n_data.js from tools/i18n/<lang>.json (Korean source string -> translation).
  python tools/i18n_extract.py   (the keys: every Korean string the page can show)
  python tools/build_i18n.py
A key missing from a language stays Korean there; the build lists how many each language lacks.
"""
import io
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
LANGS = ['ko', 'ja', 'en', 'zh-Hans', 'zh-Hant', 'pt', 'es', 'ru']
LABELS = ['한국어', '日本語', 'English', '简体中文', '繁體中文', 'Português', 'Español', 'Русский']


def main():
    keys = json.load(io.open(os.path.join(HERE, 'i18n', 'keys.json'), encoding='utf-8'))
    tables = {}
    for lg in LANGS[1:]:
        p = os.path.join(HERE, 'i18n', lg + '.json')
        tables[lg] = json.load(io.open(p, encoding='utf-8')) if os.path.exists(p) else {}
    xp = os.path.join(HERE, 'i18n', 'extra.json')  # a few strings added after the big batches: {key: {lang: text}}
    if os.path.exists(xp):
        for k, row in json.load(io.open(xp, encoding='utf-8')).items():
            keys = sorted(set(keys) | {k})
            for lg, v in row.items(): tables[lg][k] = v
    t = {}
    for k in keys:
        row = [tables[lg].get(k, '') for lg in LANGS[1:]]
        if any(row): t[k] = row
    for lg in LANGS[1:]:
        miss = [k for k in keys if not tables[lg].get(k)]
        print(lg, 'missing', len(miss))
    with io.open(os.path.join(HERE, '..', 'js', 'i18n_data.js'), 'w', encoding='utf-8') as f:
        f.write('// generated by tools/build_i18n.py from tools/i18n/*.json\n')
        f.write('window.I18N_DATA=%s;\n' % json.dumps({'langs': LANGS, 'labels': LABELS, 't': t}, ensure_ascii=False, separators=(',', ':')))
    print('i18n:', len(t), 'strings x', len(LANGS) - 1, 'languages')


if __name__ == '__main__':
    main()
