"""Build original SD rigs straight into this project: js/sd/<id>.js (+ .a50/.a35/.a100/.a75 atlases) and their
attack timing in js/anim_events.js. It runs E:/LAO_MINI_GAME/5_LAO_Defence/tools/build_sd.py with its output sent
here (that project's files stay as they are). Export the Unity meshes first (see the lao-sd-character skill).

    python tools/import_rig.py lemonadebeta=PECS_LemonadeBeta_N e_LemonadeDelta_N=Model_MP_LemonadeDelta_N
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SD = os.path.join(HERE, '..', 'js', 'sd')
SRC = r'E:\LAO_MINI_GAME\5_LAO_Defence\tools'
sys.path.insert(0, SRC)
sys.path.insert(0, HERE)
import build_sd as B  # noqa: E402
import build_events as E  # noqa: E402

pairs = [a.split('=', 1) for a in sys.argv[1:]]
for uid, model in pairs:  # an enemy SD (e_<Model>) comes from the monster folder
    if uid.startswith('e_'): B.ENEMIES[uid[2:]] = model
    else: B.UNITS[uid] = model
B.OUT = SD
_load = B.load_docs
def _str_names(o):  # a node named like a number ('1') is read as an int: the build joins names as text
    if isinstance(o, dict):
        for k, v in o.items():
            if k == 'm_Name' and not isinstance(v, str): o[k] = str(v)
            else: _str_names(v)
    elif isinstance(o, (list, tuple)):
        for v in o: _str_names(v)
    return o
B.load_docs = lambda *a, **k: _str_names(_load(*a, **k))
B.hires_ids = lambda: set()
for uid, _ in pairs:
    B.build(uid)
    print('built', uid)

# attack timing / fire points, merged into this project's table
path = os.path.join(HERE, '..', 'js', 'anim_events.js')
src = open(path, encoding='utf-8').read()
m = re.search(r'window\.ANIM_EV=(\{.*\});', src, re.S)
ev_all = json.loads(m.group(1))
for uid, model in pairs:
    if uid.startswith('e_'): continue  # (enemy SDs keep the default attack timing, like the iron units)
    cd, pf = B.find_char(model)
    an = B.find_anims(cd, model)
    if 'move' not in an or 'idle' not in an or 'atk' not in an:
        an = dict(B.pick_clips(B.controller_anims(pf)), **an)
    ev = {}
    for k in ('atk', 'skill'):
        if k in an:
            c = E.clip_events(an[k])
            if c['t']:
                ev[k] = c
    fp = E.fire_points(pf)
    if fp:
        ev['fire'] = fp
    if ev:
        ev_all[uid] = ev
with open(path, 'w', encoding='utf-8') as f:
    f.write('// generated by tools/build_events.py: attack clip timing (seconds, fire point #) and muzzle transforms\n')
    f.write('window.ANIM_EV=%s;\n' % json.dumps(ev_all, separators=(',', ':')))

# the sharper atlases
import build_hires as H  # noqa: E402
_hload = H.b.load_docs
H.b.load_docs = lambda *a, **k: _str_names(_hload(*a, **k))
for uid, model in pairs:
    if uid.startswith('e_'): H.b.ENEMIES[uid[2:]] = model
    else: H.b.UNITS[uid] = model
H.main([uid for uid, _ in pairs])
